/** @param {string} lang @returns {typeof RECORDS_TEXT.en} */
export const recordsText = (lang) => RECORDS_TEXT[lang === 'es' ? 'es' : 'en'];

/** Name of a saved view in the user's language (defaults are translated by their slug). */
export function viewName(view, defaults, lang) {
  const known = defaults.find((d) => d.slug && d.slug === view.slug);
  return known ? known.name[lang === 'es' ? 'es' : 'en'] : view.name;
}
